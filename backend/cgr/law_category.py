CATEGORY_EMOJI = {
    "개별법": "🟦",
    "산안법": "🟧",
    "단체법": "🟪",
    "기타":   "⬜",
}


def _normalize(law_name: str) -> str:
    """법령명 정규화 — 공백/괄호 제거."""
    if not law_name:
        return ""
    s = re.sub(r"\s+", " ", law_name).strip()
    # 마침표·조항 번호 제거 (앞부분 법령명만 추출)
    s = re.sub(r"\s*제\s*\d+조.*$", "", s)
    return s


def classify_law(law_name: str) -> str:
    """법령명 → 대분류 ("개별법" / "산안법" / "단체법" / "기타")."""
    s = _normalize(law_name)
    if not s:
        return "기타"
    # 정확 매칭 우선
    if s in _INDIVIDUAL:
        return "개별법"
    if s in _OSHA:
        return "산안법"
    if s in _COLLECTIVE:
        return "단체법"
    # 부분 매칭 (가장 긴 매치 우선)
    candidates = []
    for name in _INDIVIDUAL:
        if name in s:
            candidates.append(("개별법", len(name)))
    for name in _OSHA:
        if name in s:
            candidates.append(("산안법", len(name)))
    for name in _COLLECTIVE:
        if name in s:
            candidates.append(("단체법", len(name)))
    # 추가 패턴 — 정확명을 못 잡아도 "고용상~~~법" 같이 시작하면 개별법
    if re.match(r"^고용상[ 가-힣]+법", s):
        candidates.append(("개별법", 4))
    if candidates:
        candidates.sort(key=lambda x: -x[1])
        return candidates[0][0]
    return "기타"


def classify_law_label(law_label: str) -> str:
    """penalty 안의 전체 라벨에서 법령 카테고리 추출.

    예: "⚖️ 근로기준법 제93조 제1호" → "개별법"
    """
    # ⚖️ 등 이모지 제거
    s = re.sub(r"^[⚖️🟦🟧🟪⬜📋⚠️🔎\s]+", "", law_label or "")
    # 첫 등장 법령명 추출 (예: "근로기준법" "산업안전보건법" "남녀고용평등법" 등)
    m = re.search(
        r"(근로기준법|근기법|남녀고용평등(?:과 일.가정 양립 지원에 관한)? ?법(?:률)?|근로자퇴직급여 ?보장법|근퇴법|근로자의 ?날 ?제정에 ?관한 ?법률|"
        r"고용상[ 가-힣]*법(?:률)?|고연법|최저임금법|임금채권보장법|기간제[ 가-힣]*법|파견[ 가-힣]*법|외국인근로자[ 가-힣]*법|"
        r"산업안전보건법|산안법|산업재해보상보험법|산재보험법|직업안정법|고용보험법|"
        r"노동조합 ?및 ?노동관계조정법|노조법|노동조합법|근로자참여[ 가-힣]*법|근참법)",
        s,
    )
    if m:
        return classify_law(m.group(1))
    return "기타"
