"""노동법 대분류 매핑 — 학설 분류 기준.

한국 노동법은 크게 세 범주로 나뉜다:

1. **개별법** (개별적 근로관계법)
   - 사용자 vs 개별 근로자의 권리·의무를 규정
   - 근로기준법·남녀고용평등법·근로자퇴직급여보장법 등 다수

2. **단체법** (집단적 노사관계법)
   - 노동조합 vs 사용자(단체)의 관계를 규정
   - 노동조합 및 노동관계조정법·근로자참여법 등

3. **산안법** (산업안전·재해보상)
   - 안전보건·재해보상에 관한 특수법
   - 산업안전보건법·산업재해보상보험법 등

4. **기타** — 부수 인용 법령 (모자보건법·직업안정법 등)

사용 예:
    cat = classify_law("근로기준법 제93조")
    # → "개별법"
"""
